-- ADDITIVE / non-destructive migration. Does NOT reset existing tables or data.
-- Run on the intended development DB: psql -d omnistat -v ON_ERROR_STOP=1 -f migrations/003_siddartha_sprint2.sql
-- Back up important data first. Run only once per environment and track changes.
BEGIN;

-- Add processing metadata to the existing CSV upload records.
ALTER TABLE raw_csv_uploads ADD COLUMN IF NOT EXISTS processed_at TIMESTAMPTZ;
ALTER TABLE raw_csv_uploads ADD COLUMN IF NOT EXISTS row_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE raw_csv_uploads ADD COLUMN IF NOT EXISTS error_message TEXT;
ALTER TABLE raw_csv_uploads ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;

-- Line items created from POS CSV rows (parser integration by Junior/Nicholas).
-- Quantity and revenue represent a row after parsing; upload_id preserves provenance.
-- Enforce that a row belongs to the same business as its parent upload.
CREATE UNIQUE INDEX IF NOT EXISTS idx_raw_csv_upload_id_business
    ON raw_csv_uploads (id, business_id);

CREATE TABLE IF NOT EXISTS sales_line_items (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    business_id UUID NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
    upload_id UUID NOT NULL,
    business_date DATE NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    category VARCHAR(255),
    quantity INTEGER NOT NULL, -- signed amounts permit POS returns/refunds
    revenue NUMERIC(12,2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (upload_id, business_id)
        REFERENCES raw_csv_uploads(id, business_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_sales_line_items_business_date
    ON sales_line_items (business_id, business_date);
CREATE INDEX IF NOT EXISTS idx_sales_line_items_upload
    ON sales_line_items (upload_id);

-- Codes are URL-safe secrets; generated by POST /api/invites.
-- A NULL used_at means unused. Junior's 4.7 signup must atomically set used_at.
CREATE TABLE IF NOT EXISTS invites (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    code VARCHAR(64) NOT NULL UNIQUE,
    business_id UUID NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
    created_by UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role VARCHAR(50) NOT NULL DEFAULT 'employee' CHECK (role = 'employee'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    used_by UUID REFERENCES users(id) ON DELETE SET NULL,
    CHECK (expires_at > created_at)
);
CREATE INDEX IF NOT EXISTS idx_invites_business
    ON invites (business_id);

COMMIT;
